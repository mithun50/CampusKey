// Merges the researched JSON files in data/raw into data/offers.js.
// Normalizes dashes and removes stray emojis so the site follows the style rules.
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const rawDir = path.join(root, "data/raw");
const order = ["dev.json", "ai.json", "design.json", "entertainment.json", "travel.json"];
const checked = process.env.CHECKED || "28 September 2026";

function clean(v) {
  if (typeof v === "string") {
    return v
      .replace(/\s*[–—‒―]\s*/g, ", ")
      .replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}️]/gu, "")
      .replace(/&amp;/g, "&")
      .replace(/\s{2,}/g, " ")
      .trim();
  }
  if (Array.isArray(v)) return v.map(clean).filter((x) => x !== "");
  if (v && typeof v === "object") {
    const out = {};
    for (const k of Object.keys(v)) out[k] = clean(v[k]);
    return out;
  }
  return v;
}

// Entries the research found are not real student offers (no student plan, not
// tied to student status, unverifiable) or duplicate another entry. Matched by prefix.
const EXCLUDE = [
  "netflix", "jiohotstar", "jiosaavn", "gaana", "times prime",
  "the hindu", "et prime", "indian express", "hdfc bank",
  "amazon prime youth", "asi monument", "metro rail", "public library",
  "microsoft learn student ambassadors",
  "microsoft 365 a1 for students", // duplicate of Microsoft 365 A1 (Office 365 Education)
  "office 365 a1 for students", // same duplicate, from the AI research file
  "chatgpt go", "perplexity pro via airtel", // telecom or regional promos, unverifiable, not student offers
  "canva for education", // K-12 only, college students cannot claim individually
  "zoom basic", // free for everyone, not a student offer
];

// Fix categories where a research file filed an offer under the wrong heading.
const CATEGORY_FIX = {
  "apple music student": "Entertainment",
  "microsoft 365 a1": "AI and Productivity",
};

const seen = new Set();
const offers = [];
for (const f of order) {
  const p = path.join(rawDir, f);
  if (!fs.existsSync(p)) {
    console.warn(`skip ${f} (missing)`);
    continue;
  }
  const list = JSON.parse(fs.readFileSync(p, "utf8"));
  for (const raw of list) {
    const o = clean(raw);
    // Research marks retired or unavailable programs as DROPPED; keep them out of the site.
    if (/^dropped\b/i.test(o.name || "") || /^dropped\b/i.test(o.notes || "")) {
      console.warn(`drop ${o.name} (${f}): marked as dropped by research`);
      continue;
    }
    if (EXCLUDE.some((x) => (o.name || "").toLowerCase().startsWith(x))) {
      console.warn(`drop ${o.name} (${f}): excluded, not a verified student offer`);
      continue;
    }
    if (!o.steps || !o.steps.length) {
      console.warn(`drop ${o.name} (${f}): no claim steps`);
      continue;
    }
    if (!o.name || !/^https:\/\//.test(o.url || "")) {
      console.warn(`drop ${o.name || "unnamed"} (${f}): missing name or https url`);
      continue;
    }
    const key = o.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
    if (seen.has(key)) {
      console.warn(`drop duplicate ${o.name} (${f})`);
      continue;
    }
    seen.add(key);
    for (const [prefix, cat] of Object.entries(CATEGORY_FIX)) {
      if (o.name.toLowerCase().startsWith(prefix)) o.category = cat;
    }
    o.verification = o.verification && o.verification.length ? o.verification : ["See official page"];
    o.sources = (o.sources || []).filter((s) => /^https?:\/\//.test(s));
    if (!o.sources.length) o.sources = [o.url];
    o.india = ["confirmed", "likely", "unclear"].includes(o.india) ? o.india : "unclear";
    o.confidence = ["high", "medium", "low"].includes(o.confidence) ? o.confidence : "low";
    offers.push(o);
  }
}

const out =
  "// Generated by scripts/build-data.js from data/raw/*.json. Edit the raw files, then run: node scripts/build-data.js\n" +
  "window.CAMPUSKEY_DATA = " +
  JSON.stringify({ checked, offers }, null, 2) +
  ";\n";
fs.writeFileSync(path.join(root, "data/offers.js"), out);
console.log(`wrote ${offers.length} offers`);
